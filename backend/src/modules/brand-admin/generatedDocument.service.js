import { GeneratedDocument } from './generatedDocument.model.js';
import { ApiError } from '../../middleware/errorHandler.js';
import { parsePagination, paginationMeta } from '../../utils/pagination.js';
import { ServiceRequest } from '../service-requests/serviceRequest.model.js';
import { WarrantyClaim } from '../partner-warranty/warrantyClaim.model.js';
import { Brand } from '../super-admin/brand.model.js';
import { BrandSettings } from './brandSettings.model.js';
import { User } from '../auth/user.model.js';
import mongoose from 'mongoose';

export async function listDocuments(brandId, { type, page, limit, sort } = {}) {
  const query = { brand: brandId };
  if (type) query.type = type;

  const { skip, limit: lim, page: pg, sort: sortObj } = parsePagination({ page, limit, sort });
  const [items, total] = await Promise.all([
    // The recent-documents table names the customer, the appliance and who ran
    // the generation, so resolve those refs rather than returning bare ids.
    GeneratedDocument.find(query)
      .populate({
        path: 'serviceRequest',
        select: 'humanId category',
        populate: { path: 'user', select: 'name' },
      })
      .populate('generatedBy', 'name')
      .sort(sortObj)
      .skip(skip)
      .limit(lim),
    GeneratedDocument.countDocuments(query),
  ]);
  return { items, meta: paginationMeta({ page: pg, limit: lim, total }) };
}

export async function getDocument(brandId, id) {
  const doc = await GeneratedDocument.findOne({ _id: id, brand: brandId });
  if (!doc) throw new ApiError(404, 'Document not found');
  return doc;
}

async function documentSnapshot(brandId, serviceRequest, generatedByUserId) {
  if (!mongoose.isValidObjectId(serviceRequest)) throw new ApiError(400, 'Invalid service request');
  const request = await ServiceRequest.findOne({ _id: serviceRequest, brand: brandId }).populate('user', 'name').lean();
  if (!request) throw new ApiError(404, 'Service request not found');
  const [brand, settings, user, claim] = await Promise.all([
    Brand.findById(brandId).select('name supportPhone').lean(),
    BrandSettings.findOne({ brand: brandId }).select('supportPhone').lean(),
    User.findById(generatedByUserId).select('name employeeId').lean(),
    request.warrantyClaim ? WarrantyClaim.findOne({ _id: request.warrantyClaim, brand: brandId }).lean() : null,
  ]);
  return { brand: brand?.name, supportPhone: settings?.supportPhone || brand?.supportPhone,
    job: request.humanId, ticket: claim?.humanId, customer: request.user?.name,
    product: request.category, model: claim?.modelNumber, serial: claim?.serialNumber,
    status: request.status, warranty: claim?.warranty?.status, coverage: claim?.coverageDecision,
    generatedBy: user?.name, employeeId: user?.employeeId };
}

/** Store the facts used in the document so subsequent job edits do not rewrite it. */
export async function generateDocument(brandId, generatedByUserId, { type, serviceRequest, pdfUrl }) {
  const snapshot = await documentSnapshot(brandId, serviceRequest, generatedByUserId);
  return GeneratedDocument.create({
    brand: brandId,
    type,
    serviceRequest,
    generatedBy: generatedByUserId,
    pdfUrl: pdfUrl || null,
    snapshot,
  });
}

const escape = value => String(value ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
export async function printableDocument(brandId, id) {
  const doc = await getDocument(brandId, id);
  // Older rows have no snapshot; render available current facts explicitly.
  const facts = doc.snapshot || await documentSnapshot(brandId, doc.serviceRequest, doc.generatedBy);
  const fields = { 'Reference': doc.humanId, 'Generated on': doc.createdAt.toISOString(),
    'NCC Job': facts.job, 'Master Ticket': facts.ticket, 'Customer': facts.customer,
    'Product': facts.product, 'Model': facts.model, 'Serial number': facts.serial,
    'Job status': facts.status, 'Warranty status': facts.warranty, 'Coverage decision': facts.coverage,
    'Generated by': facts.generatedBy, 'Employee ID': facts.employeeId };
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${escape(doc.humanId)} — ${escape(doc.type)}</title>
    <style>body{font:16px/1.6 system-ui;margin:40px;color:#172554}h1{font-size:24px}table{width:100%;border-collapse:collapse}th,td{text-align:left;padding:10px;border-bottom:1px solid #ddd}th{width:35%}button{padding:10px;margin-bottom:20px}@media print{button{display:none}body{margin:0}}</style></head>
    <body><button onclick="window.print()">Print / Save PDF</button><header><h1>${escape(facts.brand)}</h1>${facts.supportPhone ? `<p>Support: ${escape(facts.supportPhone)}</p>` : ''}</header>
    <h2>${escape(doc.type)}</h2><table>${Object.entries(fields).filter(([, value]) => value != null && value !== '').map(([label, value]) => `<tr><th>${escape(label)}</th><td>${escape(value)}</td></tr>`).join('')}</table>
    ${!doc.snapshot ? '<p>Historical document: details reflect the current linked job.</p>' : ''}</body></html>`;
}
