import { Router } from 'express';
import { z } from 'zod';
import { validate } from '../../middleware/validate.js';
import { ok,created } from '../../utils/respond.js';
import { actorFromReq } from './actor.js';
import { id } from './registration.validation.js';
import { policySchema,evaluationSchema,importSerialsSchema } from './warrantyPolicy.validation.js';
import { formOptions } from './registration.service.js';
import { WARRANTY_STATUSES } from '../partner-warranty/ticketConstants.js';
import * as service from './warrantyPolicy.service.js';
export const warrantyPolicyRouter=Router();
const handle=(fn,response=ok)=>async(req,res,next)=>{try{response(res,await fn(req));}catch(e){next(e);}};
warrantyPolicyRouter.get('/options',handle(async req=>({...await formOptions(req.user.brand),warrantyStatuses:WARRANTY_STATUSES})));
warrantyPolicyRouter.get('/',handle(req=>service.listPolicies(req.user.brand)));
warrantyPolicyRouter.post('/',validate(policySchema),handle(async req=>service.createPolicy(req.user.brand,await actorFromReq(req),req.body),created));
warrantyPolicyRouter.post('/test',validate(evaluationSchema),handle(req=>service.evaluateWarranty({...req.body,brand:req.user.brand})));
warrantyPolicyRouter.get('/serials',validate(z.object({q:z.string().trim().max(60).default('')}),'query'),handle(req=>service.listSerials(req.user.brand,req.query.q)));
warrantyPolicyRouter.post('/serials/import',validate(importSerialsSchema),handle(async req=>service.importSerials(req.user.brand,await actorFromReq(req),req.body)));
warrantyPolicyRouter.get('/:id',validate(z.object({id}),'params'),handle(req=>service.findPolicy(req.user.brand,req.params.id)));
warrantyPolicyRouter.put('/:id',validate(z.object({id}),'params'),validate(policySchema),handle(async req=>service.versionPolicy(req.user.brand,req.params.id,await actorFromReq(req),req.body)));
warrantyPolicyRouter.delete('/:id',validate(z.object({id}),'params'),handle(async req=>service.deactivatePolicy(req.user.brand,req.params.id,await actorFromReq(req))));
