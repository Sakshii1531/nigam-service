export const INDIAN_STATES = Object.keys(STATE_CITIES);

/**
 * Retrieve the list of cities for a given state name (case-insensitive)
 * @param {string} stateName
 * @returns {string[]}
 */
export const getCitiesForState = (stateName) => {
  if (!stateName) return [];
  const normalized = String(stateName).trim().toLowerCase();
  
  // Exact match first
  if (STATE_CITIES[stateName]) {
    return STATE_CITIES[stateName];
  }

  // Alias lookup
  const ALIAS_MAP = {
    'mp': 'Madhya Pradesh',
    'up': 'Uttar Pradesh',
    'ap': 'Andhra Pradesh',
    'hp': 'Himachal Pradesh',
    'dl': 'Delhi NCR',
    'delhi': 'Delhi NCR',
    'mh': 'Maharashtra',
    'ka': 'Karnataka',
    'tn': 'Tamil Nadu',
    'ts': 'Telangana',
    'tg': 'Telangana',
    'wb': 'West Bengal',
    'rj': 'Rajasthan',
    'gj': 'Gujarat',
    'pb': 'Punjab',
    'hr': 'Haryana',
    'br': 'Bihar',
    'jh': 'Jharkhand',
    'cg': 'Chhattisgarh',
    'ch': 'Chandigarh',
    'uk': 'Uttarakhand',
    'ua': 'Uttarakhand',
    'jk': 'Jammu and Kashmir',
    'kl': 'Kerala',
    'or': 'Odisha',
    'od': 'Odisha',
    'as': 'Assam',
    'ga': 'Goa',
  };

  const aliasKey = ALIAS_MAP[normalized];
  if (aliasKey && STATE_CITIES[aliasKey]) {
    return STATE_CITIES[aliasKey];
  }

  // Case-insensitive key match
  const foundKey = Object.keys(STATE_CITIES).find(
    k => k.toLowerCase() === normalized
  );

  return foundKey ? STATE_CITIES[foundKey] : [];
};

/**
 * Normalizes state abbreviation or alias to its canonical full title
 * (e.g., "mp" or "MP" -> "Madhya Pradesh")
 * @param {string} stateInput
 * @returns {string}
 */
export const normalizeStateName = (stateInput) => {
  if (!stateInput) return '';
  const trimmed = String(stateInput).trim();
  const lower = trimmed.toLowerCase();

  const ALIAS_MAP = {
    'mp': 'Madhya Pradesh',
    'up': 'Uttar Pradesh',
    'ap': 'Andhra Pradesh',
    'hp': 'Himachal Pradesh',
    'dl': 'Delhi NCR',
    'delhi': 'Delhi NCR',
    'mh': 'Maharashtra',
    'ka': 'Karnataka',
    'tn': 'Tamil Nadu',
    'ts': 'Telangana',
    'tg': 'Telangana',
    'wb': 'West Bengal',
    'rj': 'Rajasthan',
    'gj': 'Gujarat',
    'pb': 'Punjab',
    'hr': 'Haryana',
    'br': 'Bihar',
    'jh': 'Jharkhand',
    'cg': 'Chhattisgarh',
    'ch': 'Chandigarh',
    'uk': 'Uttarakhand',
    'ua': 'Uttarakhand',
    'jk': 'Jammu and Kashmir',
    'kl': 'Kerala',
    'or': 'Odisha',
    'od': 'Odisha',
    'as': 'Assam',
    'ga': 'Goa',
  };

  if (ALIAS_MAP[lower]) return ALIAS_MAP[lower];

  const found = Object.keys(STATE_CITIES).find(k => k.toLowerCase() === lower);
  return found || trimmed;
};
